  function t(key) {
    const dict = translations[currentLang] || translations.zh;
    return dict[key] !== undefined ? dict[key] : (translations.zh[key] !== undefined ? translations.zh[key] : key);
  }

  function apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-ph"));
    });
    document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  }

  function setLang(lang) {
    currentLang = lang === "en" ? "en" : "zh";
    try { localStorage.setItem(STORAGE_KEY, currentLang); } catch (e) { /* ignore */ }
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: currentLang }));
  }

  function init() {
    let saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) { /* ignore */ }
    currentLang = saved === "en" ? "en" : "zh";
    apply();
  }

  return { t, apply, setLang, init, get lang() { return currentLang; } };
